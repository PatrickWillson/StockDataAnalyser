"""Dossier Generator orchestrator for stock analysis dossier.

This module provides the main DossierGenerator class that orchestrates the generation
of complete stock analysis dossiers by coordinating all section generators.

The DossierGenerator follows a section-based architecture where each section is
generated by a dedicated section class, allowing for independent testing and
modification of individual sections without affecting others.

Requirements: 1.1, 1.2, 1.3
"""

from typing import List, Dict, Any, Optional
from core.report_context import build_report_context
from output.sections.base import DossierSection
from output.sections.critical_alerts import CriticalAlertsSection
from output.sections.executive_summary import ExecutiveSummarySection
from output.sections.header import HeaderSection
from output.sections.key_metrics import KeyMetricsSection
from output.sections.risk_factors import RiskFactorsSection
from output.sections.methodology import MethodologySection
from output.sections.calculation_details import CalculationDetailsSection
from output.sections.graham_tests import GrahamTestsSection
from output.sections.financial_history import FinancialHistorySection
from output.sections.ttm_analysis import TTMAnalysisSection


class DossierGenerator:
    """Generates markdown dossier from financial data and metrics.
    
    This class orchestrates the generation of a complete stock analysis dossier
    by coordinating multiple section generators. Each section is responsible for
    generating its own markdown content, and the DossierGenerator assembles them
    into a complete document.
    
    The dossier includes:
    - Header with metadata (ticker, CEO, sector, currency, date)
    - Executive Summary (verdict, intrinsic values, price, dividend)
    - Key Metrics (profitability, book value, ownership, risk)
    - Risk Factors (two assessments: quantifiable and Graham-based)
    - Methodology Notes (calculation explanations)
    - Calculation Details (detailed breakdowns)
    - Graham Tests (defensive and enterprising investor tests)
    - Financial History (20-year table)
    - Critical Alerts (warnings and anomalies)
    
    Requirements: 1.1, 1.2, 1.3
    
    Attributes:
        ticker: Stock ticker symbol (e.g., 'AAPL.US', 'YU.LSE')
        financial_data: Dictionary containing financial data (FinancialData DTO)
        metrics: Dictionary containing Graham metrics (GrahamMetrics DTO)
        anomalies: List of anomaly detection results
        executive_summary: Executive summary section generator
        key_metrics: Key metrics section generator
        risk_factors: Risk factors section generator
        methodology: Methodology notes section generator
        calculation_details: Calculation details section generator
        graham_tests: Graham tests section generator
        financial_history: Financial history section generator
    """
    
    def __init__(self, ticker: str, financial_data: Dict[str, Any], 
                 metrics: Dict[str, Any], anomalies: List[str],
                 ttm_metrics: Optional[Dict[str, Any]] = None):
        """Initialize dossier generator with data and metrics.
        
        Args:
            ticker: Stock ticker symbol (e.g., 'AAPL.US', 'YU.LSE')
            financial_data: Dictionary containing financial data (FinancialData DTO)
            metrics: Dictionary containing Graham metrics (GrahamMetrics DTO)
            anomalies: List of anomaly detection results
            ttm_metrics: Optional dictionary containing TTM metrics
        """
        self.ticker = ticker
        self.financial_data = financial_data
        self.metrics = metrics
        self.anomalies = anomalies
        self.ttm_metrics = ttm_metrics
        
        # The view model, derived once in core and shared by every section
        self.context = build_report_context(financial_data, metrics)
        context = self.context
        
        # Initialize section generators
        self.header = HeaderSection(ticker, financial_data, context)
        self.executive_summary = ExecutiveSummarySection(financial_data, metrics, context)
        self.critical_alerts = CriticalAlertsSection(financial_data, metrics, anomalies)
        self.key_metrics = KeyMetricsSection(financial_data, {'current_ratio': metrics.get('current_ratio'),
                                                              'quick_ratio': metrics.get('quick_ratio'),
                                                              'nca_details': metrics.get('nca_details')}, context)
        self.risk_factors = RiskFactorsSection(financial_data, metrics, context)
        self.methodology = MethodologySection(financial_data, metrics, context)
        self.calculation_details = CalculationDetailsSection(financial_data, metrics, context)
        self.graham_tests = GrahamTestsSection(metrics)
        self.financial_history = FinancialHistorySection(financial_data, context)
        
        # Initialize TTM section if data available
        if ttm_metrics and ttm_metrics.get('ttm_graham_number') != "N/A":
            self.ttm_analysis = TTMAnalysisSection(ttm_metrics, metrics, financial_data, context)
        else:
            self.ttm_analysis = None
    
    def generate(self) -> str:
        """Generate complete dossier content.
        
        This method orchestrates the generation of all dossier sections in the
        correct order and assembles them into a complete markdown document.
        
        The generation order follows CLAUDE.md "Output Format" (decision D3):
        1. Header (metadata)
        2. Section 1: Executive Summary (then 1.5 TTM Analysis, if available)
        3. Section 2: Key Metrics
        4. Section 3: Critical Alerts (warnings and anomalies)
        5. Risk Factors
        6. Sections 4-5: Graham Tests (defensive and enterprising)
        7. Section 6: Financial History
        8. Methodology Notes and Calculation Details
        
        Returns:
            str: Complete markdown-formatted dossier as a single string
        """
        return '\n'.join(line for section in self.sections() for line in section.generate())
    
    def sections(self) -> List[DossierSection]:
        """The sections in render order (CLAUDE.md "Output Format", decision D3)."""
        ordered = [self.header, self.executive_summary]
        if self.ttm_analysis:
            ordered.append(self.ttm_analysis)
        ordered += [self.key_metrics, self.critical_alerts, self.risk_factors, self.graham_tests,
                    self.financial_history, self.methodology, self.calculation_details]
        return ordered
