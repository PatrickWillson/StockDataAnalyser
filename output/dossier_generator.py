"""Dossier Generator orchestrator for stock analysis dossier.

This module provides the main DossierGenerator class that orchestrates the generation
of complete stock analysis dossiers by coordinating all section generators.

The DossierGenerator follows a section-based architecture where each section is
generated by a dedicated section class, allowing for independent testing and
modification of individual sections without affecting others.

Requirements: 1.1, 1.2, 1.3
"""

from datetime import datetime
from typing import List, Dict, Any, Optional
from output.sections.executive_summary import ExecutiveSummarySection
from output.sections.key_metrics import KeyMetricsSection
from output.sections.risk_factors import RiskFactorsSection
from output.sections.methodology import MethodologySection
from output.sections.calculation_details import CalculationDetailsSection
from output.sections.graham_tests import GrahamTestsSection
from output.sections.financial_history import FinancialHistorySection
from output.sections.ttm_analysis import TTMAnalysisSection


class DossierGenerator:
    """Generates markdown dossier from financial data and metrics.
    
    This class orchestrates the generation of a complete stock analysis dossier
    by coordinating multiple section generators. Each section is responsible for
    generating its own markdown content, and the DossierGenerator assembles them
    into a complete document.
    
    The dossier includes:
    - Header with metadata (ticker, CEO, sector, currency, date)
    - Executive Summary (verdict, intrinsic values, price, dividend)
    - Key Metrics (profitability, book value, ownership, risk)
    - Risk Factors (two assessments: quantifiable and Graham-based)
    - Methodology Notes (calculation explanations)
    - Calculation Details (detailed breakdowns)
    - Graham Tests (defensive and enterprising investor tests)
    - Financial History (20-year table)
    - Critical Alerts (warnings and anomalies)
    
    Requirements: 1.1, 1.2, 1.3
    
    Attributes:
        ticker: Stock ticker symbol (e.g., 'AAPL.US', 'YU.LSE')
        financial_data: Dictionary containing financial data (FinancialData DTO)
        metrics: Dictionary containing Graham metrics (GrahamMetrics DTO)
        anomalies: List of anomaly detection results
        executive_summary: Executive summary section generator
        key_metrics: Key metrics section generator
        risk_factors: Risk factors section generator
        methodology: Methodology notes section generator
        calculation_details: Calculation details section generator
        graham_tests: Graham tests section generator
        financial_history: Financial history section generator
    """
    
    def __init__(self, ticker: str, financial_data: Dict[str, Any], 
                 metrics: Dict[str, Any], anomalies: List[str],
                 ttm_metrics: Optional[Dict[str, Any]] = None):
        """Initialize dossier generator with data and metrics.
        
        Args:
            ticker: Stock ticker symbol (e.g., 'AAPL.US', 'YU.LSE')
            financial_data: Dictionary containing financial data (FinancialData DTO)
            metrics: Dictionary containing Graham metrics (GrahamMetrics DTO)
            anomalies: List of anomaly detection results
            ttm_metrics: Optional dictionary containing TTM metrics
        """
        self.ticker = ticker
        self.financial_data = financial_data
        self.metrics = metrics
        self.anomalies = anomalies
        self.ttm_metrics = ttm_metrics
        
        # Initialize section generators
        self.executive_summary = ExecutiveSummarySection(financial_data, metrics)
        self.key_metrics = KeyMetricsSection(financial_data)
        self.risk_factors = RiskFactorsSection(financial_data, metrics)
        self.methodology = MethodologySection(financial_data, metrics)
        self.calculation_details = CalculationDetailsSection(financial_data, metrics)
        self.graham_tests = GrahamTestsSection(metrics)
        self.financial_history = FinancialHistorySection(financial_data)
        
        # Initialize TTM section if data available
        if ttm_metrics and ttm_metrics.get('ttm_graham_number') != "N/A":
            self.ttm_analysis = TTMAnalysisSection(ttm_metrics, metrics, financial_data)
        else:
            self.ttm_analysis = None
    
    def generate(self) -> str:
        """Generate complete dossier content.
        
        This method orchestrates the generation of all dossier sections in the
        correct order and assembles them into a complete markdown document.
        
        The generation order is:
        1. Header (metadata)
        2. Executive Summary
        3. Key Metrics
        4. Risk Factors
        5. Methodology Notes
        6. Calculation Details
        7. Graham Tests (defensive and enterprising)
        8. Financial History
        9. Critical Alerts (warnings and anomalies)
        
        Returns:
            str: Complete markdown-formatted dossier as a single string
        """
        lines = []
        
        # 1. Header with metadata
        lines.extend(self._generate_header())
        
        # 2. Executive Summary
        lines.extend(self.executive_summary.generate())
        
        # 2.5. TTM Analysis (if data available)
        if self.ttm_analysis:
            lines.extend(self.ttm_analysis.generate())
        
        # 3. Key Metrics
        lines.extend(self.key_metrics.generate())
        
        # 4. Risk Factors
        lines.extend(self.risk_factors.generate())
        
        # 5. Methodology Notes
        lines.extend(self.methodology.generate())
        
        # 6. Calculation Details
        lines.extend(self.calculation_details.generate())
        
        # 7. Graham Tests (defensive and enterprising)
        lines.extend(self.graham_tests.generate())
        
        # 8. Financial History
        lines.extend(self.financial_history.generate())
        
        # 9. Critical Alerts
        lines.extend(self._generate_critical_alerts())
        
        # Join all lines with newlines
        return '\n'.join(lines)
    
    def _generate_header(self) -> List[str]:
        """Generate dossier header with metadata.
        
        The header includes:
        - Ticker symbol
        - Generation date
        - Data source
        - CEO name
        - Sector and industry
        - Employee count
        - Most recent annual data year
        - Currency information
        
        Returns:
            List[str]: List of markdown lines for the header
        """
        lines = []
        
        # Extract metadata
        unified_currency = self.financial_data.get('currency', 'USD')
        original_stock_currency = self.financial_data.get('original_stock_currency', unified_currency)
        ceo_name = self.financial_data.get('ceo_name', 'N/A')
        sector = self.financial_data.get('sector', 'N/A')
        industry = self.financial_data.get('industry', 'N/A')
        employees = self.financial_data.get('employees', 0)
        
        # Title and basic metadata
        lines.append(f"# STOCK ANALYSIS DOSSIER: {self.ticker}")
        lines.append(f"# DATE: {datetime.now().strftime('%Y-%m-%d')}")
        lines.append(f"# SOURCE: EODHD (Tier 1 Data)")
        lines.append(f"# CEO: {ceo_name}")
        lines.append(f"# SECTOR: {sector} | INDUSTRY: {industry}")
        lines.append(f"# EMPLOYEES: {employees:,}" if employees > 0 else "# EMPLOYEES: N/A")
        
        # Add data freshness note - use most recent year with actual financial data
        history = self.financial_data.get('history', {})
        if history:
            sorted_years = sorted(history.keys(), reverse=True)
            # Find most recent year with financial data (not just dividend data)
            most_recent_year = None
            for year in sorted_years:
                year_data = history[year]
                if year_data.get('revenue', 0.0) > 0 or year_data.get('net_income', 0.0) != 0 or year_data.get('total_equity', 0.0) > 0:
                    most_recent_year = year.split('-')[0]
                    break
            
            if most_recent_year:
                lines.append(f"# MOST RECENT ANNUAL DATA: {most_recent_year}")
        
        # Add currency note if conversion was applied
        if original_stock_currency != unified_currency:
            lines.append(f"# CURRENCY: All values in {unified_currency} (stock trades in {original_stock_currency})")
        else:
            lines.append(f"# CURRENCY: {unified_currency}")
        
        lines.append("")
        lines.append("---")
        
        return lines
    
    def _generate_critical_alerts(self) -> List[str]:
        """Generate critical alerts section.
        
        This section includes:
        - Data quality warnings
        - Currency conversion details
        - Validation discrepancies
        - Statistical anomalies (Z-Score outliers)
        
        Returns:
            List[str]: List of markdown lines for critical alerts section
        """
        lines = []
        
        lines.append("")
        lines.append("## SECTION 3: CRITICAL ALERTS")
        lines.append("")
        
        # Get warnings from financial data and metrics
        warnings = self.financial_data.get('warnings', [])
        metric_warnings = self.metrics.get('warnings', [])
        all_warnings = warnings + metric_warnings
        
        # Display warnings
        if all_warnings:
            lines.append("### Data Quality & Limitations:")
            for warning in all_warnings:
                lines.append(f"- {warning}")
            lines.append("")
        
        # Display anomalies
        if self.anomalies:
            lines.append("### Statistical Anomalies (Z-Score Analysis):")
            lines.append("*Metrics that deviate significantly from historical patterns*")
            lines.append("")
            for anomaly in self.anomalies:
                lines.append(f"- {anomaly}")
            lines.append("")
        
        # If no warnings or anomalies
        if not all_warnings and not self.anomalies:
            lines.append("No critical alerts or anomalies detected.")
            lines.append("")
        
        lines.append("---")
        
        return lines
